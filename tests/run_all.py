def main():
    mp = None
    verbose = "-v" in sys.argv
    for a in sys.argv[1:]:
        if not a.startswith("-"):
            mp = a
    bad = 0
    for mod, ins in S:
        data = ("\n".join(ins) + "\n").encode()
        if mod == "CHEM":
            cmd = ([mp, "-X", "heapsize=169k"] if mp else [sys.executable]) + ["CHEM.py"]
        else:
            cmd = ([mp, "-X", "heapsize=169k"] if mp else [sys.executable]) + [os.path.join(ROOT, "tests", "mp_sim.py"), mod]
        p = subprocess.run(cmd, input=data, capture_output=True, cwd=CALC, timeout=300)
        out = (p.stdout + p.stderr).decode(errors="replace")
        prob = [l for l in out.split("\n") if "Error" in l or "Traceback" in l or "Bad number" in l
                or ("Leave exactly" in l and mod != "U1B")]
        heap = [l for l in out.split("\n") if "free heap" in l]
        if prob:
            bad += 1
            print("==", mod, "PROBLEM:", prob[:6])
        else:
            print("==", mod, "ok", heap[0] if heap else "")
        if verbose:
            print(out)
        if "-o" in sys.argv:
            open(os.path.join(ROOT, "tests", "out_" + mod + ".txt"), "w").write(out)
    sys.exit(1 if bad else 0)

main()
